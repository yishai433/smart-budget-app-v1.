const HE_MONTHS = ['ינואר','פברואר','מרץ','אפריל','מאי','יוני','יולי','אוגוסט','ספטמבר','אוקטובר','נובמבר','דצמבר']

function formatMonthKey(key, lang) {
  try {
    const [year, month] = key.split('-').map(Number)
    const name = lang === 'he' ? HE_MONTHS[month - 1] : format(new Date(year, month - 1, 1), 'MMMM')
    return `${name} ${year}`
  } catch { return key }
}

function groupByMonth(txs) {
  return txs.reduce((groups, tx) => {
    const key = (tx.date || 'unknown').substring(0, 7)
    if (!groups[key]) groups[key] = []
    groups[key].push(tx)
    return groups
  }, {})
}

function SwipeableRow({ tx, onDelete, onOpenDetail, t, catDef, cur }) {
  const x = useMotionValue(0)
  const [swiped, setSwiped] = useState(false)

  const snapTo = (val) => animate(x, val, { type: 'spring', stiffness: 420, damping: 36 })

  const handleDragEnd = (_, info) => {
    if (info.offset.x < -220 || info.velocity.x < -700) {
      onDelete(tx.id)
    } else if (info.offset.x < -50) {
      setSwiped(true)
      snapTo(-90)
    } else {
      setSwiped(false)
      snapTo(0)
    }
  }

  const handleClick = () => {
    if (swiped) {
      setSwiped(false)
      snapTo(0)
    } else {
      onOpenDetail(tx)
    }
  }

  return (
    <div style={{ position: 'relative', overflow: 'hidden' }}>
      {/* Delete strip — always present but only visible when swiped out */}
      <div style={{
        position: 'absolute', top: 0, bottom: 0, right: 0, width: 90,
        background: 'var(--c-danger)',
        display: 'flex', alignItems: 'center', justifyContent: 'center',
      }}>
        <button
          onClick={() => onDelete(tx.id)}
          style={{
            background: 'none', border: 'none',
            color: 'white', fontWeight: 600, fontSize: 12,
            cursor: 'pointer', display: 'flex', flexDirection: 'column',
            alignItems: 'center', gap: 4,
          }}
        >
          <Trash2 size={17} strokeWidth={2} />
          <span>{t('common.delete')}</span>
        </button>
      </div>

      <motion.div
        className="list-item"
        drag="x"
        dragConstraints={{ left: -300, right: 0 }}
        dragElastic={{ left: 0.06, right: 0 }}
        dragMomentum={false}
        style={{
          x,
          cursor: 'default',
          userSelect: 'none',
          background: 'var(--c-card)',
          position: 'relative',
          zIndex: 1,
          margin: 0,
        }}
        onDragEnd={handleDragEnd}
        onClick={handleClick}
      >
        <div className="list-icon" style={{ background: catDef.color + '14', color: catDef.color }}>
          <CategoryIcon id={tx.category} size={17} strokeWidth={2} />
        </div>
        <div style={{ flex: 1, minWidth: 0 }}>
          <div style={{ fontWeight: 500, fontSize: 14.5, whiteSpace: 'nowrap', overflow: 'hidden', textOverflow: 'ellipsis' }}>
            {tx.description || t(`categories.${tx.category}`)}
          </div>
          <div style={{ fontSize: 12, color: 'var(--c-text2)', marginTop: 2, display: 'flex', gap: 5, alignItems: 'center' }}>
            <span>{t(`categories.${tx.category}`)}</span>
            {tx.date && <span className="num">· {tx.date.slice(8, 10)}/{tx.date.slice(5, 7)}</span>}
            {tx.isRecurring && (
              <span style={{ color: 'var(--c-text3)', display: 'inline-flex', alignItems: 'center', gap: 3 }}>
                <Repeat size={11} strokeWidth={2} />
                {t(`transaction.${tx.frequency}`)}
                {tx.autoGenerated && ` · ${t('transaction.auto')}`}
              </span>
            )}
          </div>
        </div>
        <div dir="ltr" className="num" style={{
          fontWeight: 700,
          fontSize: 15,
          color: tx.type === 'income' ? 'var(--c-success)' : '#D94949',
          letterSpacing: -0.2,
          flexShrink: 0,
        }}>
          {formatMoney(tx.amount, tx.type, cur)}
        </div>
      </motion.div>
    </div>
  )
}

function formatFullDate(dateStr) {
  try { return new Date(dateStr).toLocaleDateString('he-IL', { day: 'numeric', month: 'long', year: 'numeric' }) }
  catch { return dateStr }
}

function DetailRow({ label, icon: Icon, children }) {
  return (
    <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center', padding: '12px 0', gap: 12 }}>
      <span style={{ fontSize: 13, color: 'var(--c-text2)', display: 'flex', alignItems: 'center', gap: 7 }}>
        {Icon && <Icon size={15} strokeWidth={2} style={{ color: 'var(--c-text3)' }} />}
        {label}
      </span>
      <span style={{ fontSize: 14, fontWeight: 500, textAlign: 'end' }}>{children}</span>
    </div>
  )
}

function EditTransactionSheet({ tx, cats, cur, t, onSave, onClose }) {
  useScrollLock()
  const [amountStr, setAmountStr] = useState(String(tx.amount ?? ''))
  const [description, setDescription] = useState(tx.description || '')
  const [category, setCategory] = useState(tx.category || '')
  const [date, setDate] = useState(tx.date || '')

  const handleAmountChange = (e) => {
    const val = e.target.value.replace(/[^0-9.]/g, '')
    const parts = val.split('.')
    if (parts.length > 2) return
    if (parts[1] && parts[1].length > 2) return
    setAmountStr(val)
  }
  const actualAmount = parseFloat(amountStr) || 0
  const canSave = actualAmount > 0 && category

  const handleSave = async () => {
    if (!canSave) return
    await onSave(tx.id, { amount: actualAmount, description, category, date })
    onClose()
  }

  return createPortal((
    <>
      <motion.div className="sheet-overlay"
        initial={{ opacity: 0 }} animate={{ opacity: 1 }} exit={{ opacity: 0 }}
        onClick={onClose}
      />
      <div className="sheet-viewport">
        <motion.div className="sheet"
          initial={{ y: '100%' }} animate={{ y: 0 }} exit={{ y: '100%' }}
          transition={{ type: 'spring', stiffness: 380, damping: 36 }}
        >
          <div className="sheet-handle" />
          <div className="sheet-header">
            <h2 className="sheet-title">עריכת עסקה</h2>
            <button onClick={onClose} className="btn-icon" style={{ width: 32, height: 32 }}>
              <X size={17} strokeWidth={2} />
            </button>
          </div>

          <div className="sheet-body" style={{ gap: 12 }}>
            <div style={{ display: 'grid', gridTemplateColumns: '5fr 7fr', gap: 10 }}>
              <div className="input-group" style={{ marginBottom: 0 }}>
                <label className="input-label">סכום (₪)</label>
                <input
                  className="input-field"
                  type="text"
                  inputMode="decimal"
                  placeholder="0.00"
                  value={amountStr}
                  onChange={handleAmountChange}
                  style={{ textAlign: 'center', fontWeight: 800, fontSize: 20 }}
                />
              </div>
              <div className="input-group" style={{ marginBottom: 0 }}>
                <label className="input-label">{t('transaction.description')}</label>
                <input
                  className="input-field"
                  placeholder={t('transaction.descriptionPlaceholder')}
                  value={description}
                  onChange={e => setDescription(e.target.value)}
                  style={{ textAlign: 'center' }}
                />
              </div>
            </div>

            <div className="input-group" style={{ marginBottom: 0 }}>
              <label className="input-label">{t('transaction.category')}</label>
              <div className="cat-grid">
                {cats.map(cat => (
                  <button
                    key={cat.id}
                    className={`cat-btn ${category === cat.id ? 'selected' : ''}`}
                    onClick={() => setCategory(cat.id)}
                    style={category === cat.id
                      ? { borderColor: cat.color, background: cat.color + '18' }
                      : {}}
                  >
                    <div className="cat-icon" style={{ color: category === cat.id ? cat.color : 'var(--c-text2)' }}>
                      <CategoryIcon id={cat.id} size={26} />
                    </div>
                    <span className="cat-label">{t(`categories.${cat.id}`)}</span>
                  </button>
                ))}
              </div>
            </div>

            <div className="input-group" style={{ marginBottom: 0 }}>
              <label className="input-label">{t('transaction.date')}</label>
              <input className="input-field" type="date" value={date} onChange={e => setDate(e.target.value)} />
            </div>
          </div>

          <div className="sheet-footer">
            <button
              className="btn btn-primary btn-full"
              onClick={handleSave}
              disabled={!canSave}
              style={{ opacity: canSave ? 1 : 0.45, transition: 'opacity 0.2s' }}
            >
              שמור שינויים
            </button>
          </div>
        </motion.div>
      </div>
    </>
  ), document.body)
}

function TransactionDetailSheet({ tx, catDef, cur, t, onDelete, onEdit, onClose }) {
  useScrollLock()
  const isIncome = tx.type === 'income'
  // Portal to <body> — the routed page this list lives in is a descendant of
  // AnimatedRoutes' will-change:transform wrapper, which becomes the
  // containing block for position:fixed children and breaks their placement
  // (the sheet would render relative to the full scrollable page height
  // instead of the viewport). AddTransaction avoids this by mounting at the
  // App root; a portal gets the same effect from anywhere in the tree.
  return createPortal((
    <>
      <motion.div className="sheet-overlay"
        initial={{ opacity: 0 }} animate={{ opacity: 1 }} exit={{ opacity: 0 }}
        onClick={onClose}
      />
      <div className="sheet-viewport">
        <motion.div className="sheet"
          initial={{ y: '100%' }} animate={{ y: 0 }} exit={{ y: '100%' }}
          transition={{ type: 'spring', stiffness: 380, damping: 36 }}
        >
          <div className="sheet-handle" />
          <div className="sheet-header">
            <div style={{ display: 'flex', alignItems: 'center', gap: 12, minWidth: 0 }}>
              <div className="list-icon" style={{ background: catDef.color + '14', color: catDef.color, width: 40, height: 40 }}>
                <CategoryIcon id={tx.category} size={19} strokeWidth={2} />
              </div>
              <div style={{ minWidth: 0 }}>
                <h2 className="sheet-title" style={{ fontSize: 16, whiteSpace: 'nowrap', overflow: 'hidden', textOverflow: 'ellipsis' }}>
                  {tx.description || t(`categories.${tx.category}`)}
                </h2>
                <div style={{ fontSize: 12, color: 'var(--c-text2)', marginTop: 1 }}>
                  {t(`categories.${tx.category}`)}
                </div>
              </div>
            </div>
            <button onClick={onClose} className="btn-icon" style={{ width: 32, height: 32, flexShrink: 0 }}>
              <X size={17} strokeWidth={2} />
            </button>
          </div>

          <div className="sheet-body">
            <div style={{
              textAlign: 'center', padding: '18px 0',
              background: 'var(--c-bg)', borderRadius: 'var(--r-md)',
              border: '1px solid var(--c-border)',
            }}>
              <div dir="ltr" className="num" style={{
                fontSize: 30, fontWeight: 700, letterSpacing: -1,
                color: isIncome ? 'var(--c-success)' : 'var(--c-danger)',
              }}>
                {formatMoney(tx.amount, tx.type, cur)}
              </div>
            </div>

            <div style={{
              border: '1px solid var(--c-border)', borderRadius: 'var(--r-md)',
              padding: '2px 14px',
            }}>
              <DetailRow label={t('transaction.date')} icon={CalendarDays}>
                {formatFullDate(tx.date)}
              </DetailRow>
              <div style={{ borderTop: '1px solid var(--c-sep)' }} />
              <DetailRow label={t('transaction.category')} icon={Tag}>
                {t(`categories.${tx.category}`)}
              </DetailRow>
              {tx.isRecurring && (
                <>
                  <div style={{ borderTop: '1px solid var(--c-sep)' }} />
                  <DetailRow label={t('transaction.isRecurring')} icon={Repeat}>
                    {t(`transaction.${tx.frequency}`)}
                  </DetailRow>
                </>
              )}
            </div>
          </div>

          <div className="sheet-footer">
            <div style={{ display: 'flex', gap: 8 }}>
              <button
                className="btn btn-danger"
                onClick={() => { onDelete(tx.id); onClose() }}
                style={{ flex: 1 }}
              >
                <Trash2 size={16} strokeWidth={2} />
                {t('common.delete')}
              </button>
              <button
                className="btn btn-primary"
                onClick={() => onEdit(tx)}
                style={{ flex: 2 }}
              >
                <Pencil size={16} strokeWidth={2} />
                עריכה
              </button>
            </div>
          </div>
        </motion.div>
      </div>
    </>
  ), document.body)
}

export default function TransactionList({ filter = 'all' }) {
  const { t, i18n } = useTranslation()
  const { transactions, deleteTransaction, updateTransaction, CATEGORIES, settings, monthKey, isCurrentMonth } = useApp()
  const cur = settings.currency
  const [detailTx, setDetailTx] = useState(null)
  const [editingTx, setEditingTx] = useState(null)

  const getCatDef = (tx) => CATEGORIES[tx.type]?.find(c => c.id === tx.category)
    || { emoji: tx.type === 'income' ? '💰' : '💸', color: '#8A8272' }

  // "All" follows the month picked in the month switcher; "recurring" lists
  // every recurring transaction regardless of month, as before.
  const filtered = filter === 'recurring'
    ? transactions.filter(tx => tx.isRecurring)
    : transactions.filter(tx => tx.date?.startsWith(monthKey))

  if (filtered.length === 0) {
    return (
      <div className="empty-state">
        <div className="empty-icon"><Receipt size={22} strokeWidth={1.8} /></div>
        <h3>{t('budget.noTransactions')}</h3>
        {(isCurrentMonth || filter === 'recurring') && <p>{t('budget.noTransactionsHint')}</p>}
      </div>
    )
  }

  const groups = groupByMonth(filtered)
  const lang = i18n.language

  return (
    <div style={{ display: 'flex', flexDirection: 'column', gap: 0 }}>
      {Object.entries(groups).map(([monthKey, txs]) => (
        <div key={monthKey} style={{ marginBottom: 18 }}>
          <div className="section-label" style={{ padding: '6px 20px 8px' }}>
            {formatMonthKey(monthKey, lang)}
          </div>
          <div style={{ margin: '0 16px' }}>
            <AnimatePresence initial={false}>
              {txs.map((tx, i) => {
                const catDef = getCatDef(tx)

                return (
                  <motion.div
                    key={tx.id}
                    initial={{ opacity: 0, y: 8 }}
                    animate={{ opacity: 1, y: 0 }}
                    exit={{ opacity: 0, height: 0 }}
                    transition={{ delay: Math.min(i, 8) * 0.03, duration: 0.22 }}
                    style={{ borderBottom: i < txs.length - 1 ? '1px solid var(--c-sep)' : 'none', background: 'transparent' }}
                  >
                    <SwipeableRow
                      tx={tx}
                      onDelete={deleteTransaction}
                      onOpenDetail={setDetailTx}
                      t={t}
                      catDef={catDef}
                      cur={cur}
                    />
                  </motion.div>
                )
              })}
            </AnimatePresence>
          </div>
        </div>
      ))}

      <AnimatePresence>
        {detailTx && (
          <TransactionDetailSheet
            tx={detailTx}
            catDef={getCatDef(detailTx)}
            cur={cur}
            t={t}
            onDelete={deleteTransaction}
            onEdit={(tx) => { setDetailTx(null); setEditingTx(tx) }}
            onClose={() => setDetailTx(null)}
          />
        )}
      </AnimatePresence>

      <AnimatePresence>
        {editingTx && (
          <EditTransactionSheet
            tx={editingTx}
            cats={CATEGORIES[editingTx.type]}
            cur={cur}
            t={t}
            onSave={updateTransaction}
            onClose={() => setEditingTx(null)}
          />
        )}
      </AnimatePresence>
    </div>
  )
}
